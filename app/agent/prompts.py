"""Agent 系统提示词。

设计原则
--------
1. **协议固定、内容自由**：输出必须是单个 JSON 对象，但思考内容完全交给模型。
2. **数据只能来自工具**：明确禁止模型自己"估"价格、涨跌幅、财务数字。
3. **给分析框架，不给结论模板**：告诉它怎么想（组合→个股→交叉验证），
   而不是告诉它结论长什么样，否则五个问题会得到五个一样的回答。

实现注意：提示词正文里包含大量 JSON 示例的 `{` `}`，因此一律使用**普通字符串**
+ `__PROTOCOL__` / `__TOOLS__` / `__RULES__` 三个标记做替换，不用 f-string，
避免 Python 把 `{"thought": ...}` 当成表达式求值。
"""

