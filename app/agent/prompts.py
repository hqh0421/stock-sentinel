# ---------------------------------------------------------------------------
# 四池口径渲染：提示词里所有比例 / 阈值都来自 decision_rules.json，不写死。
# get_rules() 按文件 mtime 热更新，界面改完比例，下一次组装提示词即同步。
# 渲染失败时回退到「不给数字、只准查工具」，绝不退回硬编码旧值误导模型。
# ---------------------------------------------------------------------------

_POOL_ACTION_LABELS = {
    "halve_if_no_start": "减半",
    "clear": "清仓",
    "halve": "减半",
    "review": "复盘",
}
_CASH_PRIORITY_LABELS = {
    "catalyst_planned_add": "催化计划内加仓",
    "dividend_extreme_small_add": "股息极端补仓",
}
_CASH_PROHIBITED_LABELS = {
    "long_track_backstop": "长赛道",
    "value_backstop": "低估",
}
_FALLBACK_BRIEF = "四池与现金的目标占比以 get_allocation_advice 返回为准"
_FALLBACK_DISCIPLINE = "各池纪律以 get_allocation_advice 与 decision_rules 返回为准"


def _num(value: Any, suffix: str = "%") -> str:
    """20.0 → "20%"、7.5 → "7.5%"、-25.0 → "-25%"；空值返回空串。"""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return ""
    return f"{number:g}{suffix}"


def _take_profit_bits(meta: Dict[str, Any]) -> List[str]:
    bits: List[str] = []
    for step in meta.get("take_profit") or []:
        if not isinstance(step, dict):
            continue
        trigger = _num(step.get("trigger_pct"))
        sell = _num(step.get("sell_pct"))
        if trigger and sell:
            text = f"+{trigger} 卖 {sell}"
            if step.get("recover_principal"):
                text += " 收回本金"
            bits.append(text)
        else:
            note = str(step.get("note") or "").split("，")[0].split("(")[0].strip()
            if note:
                bits.append(note)
    return bits


def _pool_discipline_bits(meta: Dict[str, Any]) -> List[str]:
    bits: List[str] = []
    time_rules = meta.get("time_rules")
    if isinstance(time_rules, dict) and time_rules:
        review_weeks = _num(time_rules.get("review_weeks"), " 周")
        if review_weeks:
            action = _POOL_ACTION_LABELS.get(str(time_rules.get("review_action") or ""), "复盘")
            bits.append(f"{review_weeks}无启动{action}")
        hard_weeks = _num(time_rules.get("hard_stop_weeks"), " 周")
        if hard_weeks:
            action = _POOL_ACTION_LABELS.get(str(time_rules.get("hard_stop_action") or ""), "离场")
            bits.append(f"满 {hard_weeks}无条件{action}")
    else:
        bits.append("无时间止损")

    review_dd = _num(meta.get("review_dd_pct"))
    if review_dd:
        bits.append(f"{review_dd} 复盘")
    stop_loss = _num(meta.get("stop_loss_pct"))
    if stop_loss:
        bits.append(f"{stop_loss} 止损")

    add = meta.get("add_rules")
    if isinstance(add, dict) and add:
        max_adds = add.get("max_adds")
        if max_adds == 0:
            bits.append("一次性建仓且禁止加仓" if add.get("mode") == "one_shot" else "禁止加仓")
        elif isinstance(add.get("require"), str) and add["require"].strip():
            bits.append(f"只在{add['require'].strip()}的回调加仓")

    bits.extend(_take_profit_bits(meta))
    return bits


def render_pool_brief() -> str:
    """四池 + 现金的目标占比与区间，用于 BASE_RULES 12.1。"""
    try:
        pools = decision_rules.pools()
        parts: List[str] = []
        for key in decision_rules.pool_order():
            meta = pools.get(key) or {}
            target = _num(meta.get("target_pct"))
            low = _num(meta.get("min_pct"), "")
            high = _num(meta.get("max_pct"), "")
            band = f"（{low}~{high}%）" if low and high else ""
            parts.append(f"{meta.get('label') or key} {target}{band}")
        cash = decision_rules.cash_rules()
        parts.append(f"现金 {_num(cash.get('target_pct'))}（下限 {_num(cash.get('min_pct'))}）")
        return " / ".join(parts) if parts else _FALLBACK_BRIEF
    except Exception as exc:  # noqa: BLE001
        logger.warning("四池占比提示词渲染失败，回退到只准查工具 error=%r", exc)
        return _FALLBACK_BRIEF


def render_pool_discipline() -> str:
    """各池时间止损 / 复盘线 / 加仓 / 止盈阶梯 + 现金用途，用于 BASE_RULES 12.2。"""
    try:
        pools = decision_rules.pools()
        parts: List[str] = []
        for key in decision_rules.pool_order():
            meta = pools.get(key) or {}
            bits = _pool_discipline_bits(meta)
            if bits:
                parts.append(f"{meta.get('label') or key}：{'、'.join(bits)}")
        cash = decision_rules.cash_rules()
        priority = [_CASH_PRIORITY_LABELS.get(str(x), str(x)) for x in cash.get("priority") or []]
        prohibited = [_CASH_PROHIBITED_LABELS.get(str(x), str(x)) for x in cash.get("prohibited") or []]
        cash_bits: List[str] = []
        if priority:
            cash_bits.append("现金只补给" + "与".join(priority))
        if prohibited:
            cash_bits.append("**禁止给" + "/".join(prohibited) + "兜底**")
        if cash_bits:
            parts.append("，".join(cash_bits))
        return "；".join(parts) + "。" if parts else _FALLBACK_DISCIPLINE
    except Exception as exc:  # noqa: BLE001
        logger.warning("四池纪律提示词渲染失败，回退到只准查工具 error=%r", exc)
        return _FALLBACK_DISCIPLINE


def build_system_prompt(scenario: str, tool_list: str) -> str:
    """组装某个场景的完整系统提示词。

    四池口径每次组装都重新渲染，保证界面改完比例后提示词立即同步，
    不会出现「界面 25%、Agent 还说 20%」的口径打架。
    """
    body = _BODIES.get(scenario) or _BODIES["copilot"]
    rules = (BASE_RULES
             .replace("__POOL_BRIEF__", render_pool_brief())
             .replace("__POOL_DISCIPLINE__", render_pool_discipline()))
    return (body
            .replace("__PROTOCOL__", PROTOCOL)
            .replace("__TOOLS__", tool_list)
            .replace("__RULES__", rules))
